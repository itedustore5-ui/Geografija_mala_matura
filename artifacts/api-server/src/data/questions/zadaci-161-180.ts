/**
 * Висина уписана бројем и јединицом, са допуном из решења или без ње.
 *
 * Јединица је обавезна: решење у 179 даје „0 m надморске висине или 0 m Н. В.“,
 * оба пута са јединицом, па голи број не носи поен ни овде. Ознака „m“ се
 * признаје и ћирилицом („м“) — у школи се метри пишу и тако, а то није избор
 * писма за сам одговор, него за ознаку мерне јединице.
 */
function withUnit(n: string, suffixes: string[]): string[] {
  // „0m“ без размака је куцање, не знање, па пролази као и „0 m“.
  const units = [`${n} m`, `${n}m`, `${n} м`, `${n}м`, `${n} метара`];
  return units.flatMap((u) => ["", ...suffixes].map((s) => `${u}${s}`));
}

