// Модел задатака прати Збирку задатака за завршни испит у основном образовању
// и васпитању (ЗВКОВ, 2025/2026), део ГЕОГРАФИЈА: задаци 121–240, у једном низу.
//
// Збирка ни географију не дели на нивое ни области — задаци иду редом, без
// наслова између, а шифре стандарда уз задатке не пише. Апликација не измишља
// своју поделу: целине за вежбање су само узастопни бројеви из збирке, по
// двадесет, па ученик увек зна где је у књизи. Целина се зато изводи из броја
// задатка и не пише се на задатак.

export type BlockKey =
  | "121-140"
  | "141-160"
  | "161-180"
  | "181-200"
  | "201-220"
  | "221-240";

export type Block = {
  key: BlockKey;
  from: number;
  to: number;
  label: string;
  /** Стране збирке на којима стоје задаци целине. */
  pages: string;
};

export const BLOCKS: Block[] = [
  { key: "121-140", from: 121, to: 140, label: "Задаци 121–140", pages: "стр. 34–38" },
  { key: "141-160", from: 141, to: 160, label: "Задаци 141–160", pages: "стр. 39–42" },
  { key: "161-180", from: 161, to: 180, label: "Задаци 161–180", pages: "стр. 42–48" },
  { key: "181-200", from: 181, to: 200, label: "Задаци 181–200", pages: "стр. 48–53" },
  { key: "201-220", from: 201, to: 220, label: "Задаци 201–220", pages: "стр. 54–58" },
  { key: "221-240", from: 221, to: 240, label: "Задаци 221–240", pages: "стр. 58–62" },
];

export const isBlockKey = (value: unknown): value is BlockKey =>
  BLOCKS.some((b) => b.key === value);

/** Целина којој задатак припада; `null` за задатке ван збирке (тестови). */
export const blockOf = (id: number): BlockKey | null =>
  BLOCKS.find((b) => id >= b.from && id <= b.to)?.key ?? null;

/**
 * Табела уз задатак (протицај и водостај Дунава у 181). Чува се као текст, а
 * не као исечена слика: на телефону се слика табеле смањи до нечитљивости, а
 * табела у HTML-у се прелама и скролује.
 */
export type TableCell = string | { text: string; rowSpan?: number; colSpan?: number };

export type DataTable = {
  caption?: string;
  head: TableCell[];
  rows: TableCell[][];
};

/**
 * Текст задатка се преписује дословно. Подебљано у књизи пише се између две
 * звездице: „Обој **кружиће** испред тачних одговора“ је једини знак да се
 * бира више одговора, а подебљани појмови у реченици („**набирање** /
 * **раседање**“) су они између којих се бира.
 */
type Base = {
  /** Број задатка у збирци — исти онај који ученик види у књизи. */
  id: number;
  /** Кључ текста из теста са завршног испита; задаци из збирке га немају. */
  textKey?: string;
  points: number;
  question: string;
  /** Увод који стоји изнад захтева. */
  passage?: string;
  source?: string;
  /**
   * Назив слике у `public/images/` (карта, график, цртеж). Чува се само
   * назив: путању гради клијент, па премештање фолдера не тражи измену
   * података о задацима.
   */
  image?: string;
  table?: DataTable;
  explanation: string;
  /**
   * Пола бода на тесту са завршног испита, онако како га предвиђа упутство за
   * прегледање: тачно је све осим једне ставке, а та ставка је остављена
   * празна („тачна два одговора и ниједан нетачан – 0,5 бодова“). Стоји само
   * на задацима где упутство то изричито каже; без поља задатак носи 1 или 0.
   * Вежбање из збирке га не користи — тамо се бодује 0/1.
   */
  halfPoint?: boolean;
};

/** Обој кружић испред тачног одговора. */
export type SingleQ = Base & {
  type: "single";
  options: string[];
  /**
   * Кад су понуђени одговори слике („обој кружић испод оног који…“), ово су
   * називи слика редом; `options` су тада само натписи испод њих.
   */
  optionImages?: string[];
  correctAnswer: number;
};

/** Обој кружиће испред свих тачних одговора. */
export type MultiQ = Base & {
  type: "multi";
  options: string[];
  optionImages?: string[];
  correctAnswers: number[];
};

/**
 * Напиши / допуни одговор. Свако поље има своју листу прихватљивих облика.
 * Први облик је онај који ученик види као тачан одговор после провере.
 */
export type FillQ = Base & {
  type: "fill";
  fields: { label: string; accepted: string[] }[];
  hint?: string;
};

/**
 * Повежи ставке леве и десне колоне, у сваком реду тачно један избор.
 * Збирка географије га не користи — види `GridQ` — али тип остаје због
 * тестова са претходних испита.
 */
export type MatchQ = Base & {
  type: "match";
  leftItems: string[];
  rightItems: string[];
  /** correctPairs[индекс леве ставке] = индекс десне ставке. */
  correctPairs: number[];
  /** Тачно је када десна колона има ставки више него лева („једна је вишак“). */
  extraRight?: boolean;
};

/** Поређај ставке по траженом редоследу. */
export type OrderQ = Base & {
  type: "order";
  items: string[];
  /** correctOrder[индекс ставке] = позиција (1-базно). */
  correctOrder: number[];
};

/** Тачно / нетачно по тврдњи. */
export type TrueFalseQ = Base & {
  type: "tf";
  statements: string[];
  /** correct[i] = тачна вредност тврдње i. */
  correct: boolean[];
  /** Натписи колона; подразумевано „Тачно“/„Нетачно“. */
  trueLabel?: string;
  falseLabel?: string;
};

/**
 * Табела „обој кружић у одговарајућем пољу“. Ученик боји које год кружиће
 * хоће, као на папиру: у реду их може бити више (глобус и карта у 124) или
 * ниједан (у 187 мала тамна небеска тела немају своју колону).
 *
 * `grid` су СВЕ такве табеле у збирци, и оне у којима сваки ред има тачно
 * један кружић. Да су те друге `match` (у реду се бира само један), ученик би
 * по понашању табеле знао у ком задатку је неки ред празан или двострук — а
 * збирка то не каже.
 *
 * Табела се чува онако како стоји у књизи — редови и колоне се не окрећу.
 * `correctCells[ред]` = колоне чији кружић у том реду треба обојити.
 */
export type GridSpec = {
  rows: string[];
  columns: string[];
  /** Кад су заглавља колона цртежи (картографски знаци, профили терена). */
  columnImages?: string[];
  /** Кад су натписи редова цртежи (шеме изохипси у 180). */
  rowImages?: string[];
  correctCells: number[][];
};

export type GridQ = Base & GridSpec & { type: "grid" };

/**
 * Подвуци / обој кружиће испод тражених речи у датом тексту.
 * У збирци из географије нема таквих задатака; тип остаје због тестова са
 * претходних испита и да бодовање остане исто као код других предмета.
 */
export type PickQ = Base & {
  type: "pick";
  tokens: string[];
  correctTokens: number[];
};

/**
 * Одговор који ученик пише слободно. Сервер га НЕ бодује: погрешно бодовање
 * слободног текста искривило би статистику. После предаје се приказује модел
 * одговора.
 */
export type OpenQ = Base & {
  type: "open";
  /** Оквирни број редова поља за одговор. */
  lines?: number;
  acceptable: string;
  unacceptable?: string;
};

/**
 * Део задатка који збирка дели на „1. … 2. …“ или „А) … Б) …“, а бодује као
 * један задатак.
 *
 * Избор једног одговора стоји или у списку испод захтева, или у самој
 * реченици — „Србија / Шпанија“ са кружићем испод појма (`inline`), како је у
 * збирци. Реченица се тада чува у два дела, пре и после места избора, да се
 * на екрану кружићи нађу испод појмова, а не у засебној листи.
 */
export type ChoicePart = {
  kind: "choice";
  /** Ознака као у збирци: „1.“, „А)“. */
  label?: string;
  /** Захтев дела, или почетак реченице кад избор стоји у њој. */
  text: string;
  /** Наставак реченице после места избора. Само уз `inline`. */
  after?: string;
  inline?: boolean;
  options: string[];
  correctAnswer: number;
};

/** Табела као део задатка (128 А: картографски знаци, па Б избор групе). */
export type GridPart = GridSpec & {
  kind: "grid";
  label?: string;
  text: string;
};

export type Part = ChoicePart | GridPart;

/**
 * Задатак од више делова. Поен се добија кад су тачни сви делови — као и код
 * табела тачно/нетачно, где се бодује цела табела. На тесту са завршног
 * испита делови се рачунају делимично (`exam-scoring.ts`).
 *
 * Раније (у апликацији за српски) такав задатак је постајао један `multi` са
 * ставкама „А. …“ и „Б. …“; то не спречава ученика да у истом делу обоји два
 * кружића, а избор у реченици се тако не може ни нацртати.
 */
export type PartsQ = Base & {
  type: "parts";
  parts: Part[];
};

export type Question =
  | SingleQ
  | MultiQ
  | FillQ
  | MatchQ
  | OrderQ
  | TrueFalseQ
  | GridQ
  | PickQ
  | OpenQ
  | PartsQ;

/** Типови које сервер уме да бодује; `open` намерно није међу њима. */
export const SCORED_TYPES = [
  "single",
  "multi",
  "fill",
  "match",
  "order",
  "tf",
  "grid",
  "pick",
  "parts",
] as const;

export const isScored = (q: Question) =>
  (SCORED_TYPES as readonly string[]).includes(q.type);

/** Текст уз тест са завршног испита. */
export type SelectedText = {
  key: string;
  title: string;
  author?: string;
  /** Пасуси; празан низ раздваја строфе. */
  body: string[];
  note?: string;
};

/**
 * Прихватљиви облици кад се тражи више појмова, а редослед није битан.
 *
 * Једно поље уместо по једног за сваки појам: са више поља ученик који исти
 * појам упише двапут добио би поен. Прима сваки редослед, са зарезима или са
 * „и“ пре последњег појма.
 */
export function anyOrder(parts: string[]): string[] {
  const permutations = (list: string[]): string[][] =>
    list.length <= 1
      ? [list]
      : list.flatMap((item, i) =>
          permutations([...list.slice(0, i), ...list.slice(i + 1)]).map((rest) => [item, ...rest]),
        );

  const out = new Set<string>();
  for (const p of permutations(parts)) {
    out.add(p.join(", "));
    out.add(`${p.slice(0, -1).join(", ")} и ${p[p.length - 1]}`);
  }
  return [...out];
}
